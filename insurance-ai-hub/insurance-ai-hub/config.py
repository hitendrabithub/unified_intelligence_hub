SQL_ACCEPTANCE_RATE = """
SELECT ROUND(AVG(CASE WHEN ACCEPTED THEN 1 ELSE 0 END) * 100, 1) AS ACCEPTANCE_RATE_PCT,
    ROUND(AVG(FEEDBACK_RATING), 2) AS AVG_RATING, COUNT(*) AS TOTAL_FEEDBACK
FROM INSURANCE_AI_HUB.ANALYTICS.RECOMMENDATION_FEEDBACK"""

SQL_ACCEPTANCE_BY_PRODUCT = """
SELECT pr.PRODUCT_NAME, pr.POLICY_TYPE, pr.PLAN_TIER,
    COUNT(f.FEEDBACK_ID) AS FEEDBACK_COUNT,
    ROUND(AVG(CASE WHEN f.ACCEPTED THEN 1 ELSE 0 END) * 100, 1) AS ACCEPTANCE_RATE,
    ROUND(AVG(f.FEEDBACK_RATING), 2) AS AVG_RATING,
    ROUND(AVG(r.MATCH_SCORE), 1) AS AVG_MATCH_SCORE
FROM INSURANCE_AI_HUB.ANALYTICS.RECOMMENDATIONS r
JOIN INSURANCE_AI_HUB.ANALYTICS.PRODUCTS pr ON r.PRODUCT_ID = pr.PRODUCT_ID
JOIN INSURANCE_AI_HUB.ANALYTICS.RECOMMENDATION_FEEDBACK f ON r.RECOMMENDATION_ID = f.RECOMMENDATION_ID
GROUP BY pr.PRODUCT_NAME, pr.POLICY_TYPE, pr.PLAN_TIER
HAVING COUNT(f.FEEDBACK_ID) >= 3 ORDER BY ACCEPTANCE_RATE DESC"""

SQL_SCORE_DISTRIBUTION = """
SELECT CASE
    WHEN MATCH_SCORE < 50 THEN '0-49' WHEN MATCH_SCORE < 60 THEN '50-59'
    WHEN MATCH_SCORE < 70 THEN '60-69' WHEN MATCH_SCORE < 80 THEN '70-79'
    WHEN MATCH_SCORE < 90 THEN '80-89' ELSE '90-100'
    END AS SCORE_RANGE, COUNT(*) AS REC_COUNT
FROM INSURANCE_AI_HUB.ANALYTICS.RECOMMENDATIONS GROUP BY SCORE_RANGE ORDER BY SCORE_RANGE"""


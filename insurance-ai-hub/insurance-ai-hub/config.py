SQL_HOME_HIGH_RISK_SEGMENTS = """
SELECT p.POLICY_TYPE, p.PLAN_TIER,
    ROUND(AVG(p.LOSS_RATIO), 3) AS AVG_LOSS_RATIO,
    COUNT(*) AS POLICY_COUNT,
    ROUND(SUM(p.PREMIUM_AMOUNT), 2) AS PREMIUM_EXPOSURE
FROM INSURANCE_AI_HUB.ANALYTICS.POLICIES p
WHERE p.POLICY_STATUS = 'Active' AND p.LOSS_RATIO > 0.7
GROUP BY p.POLICY_TYPE, p.PLAN_TIER
ORDER BY AVG_LOSS_RATIO DESC
LIMIT 5"""

SQL_HOME_CRITICAL_DQ_ISSUES = """
SELECT r.RULE_NAME, r.TARGET_TABLE, r.SEVERITY,
    res.PASS_RATE, res.FAILED_RECORDS
FROM INSURANCE_AI_HUB.DATA_QUALITY.DQ_RULES r
JOIN INSURANCE_AI_HUB.DATA_QUALITY.DQ_RESULTS res ON r.RULE_ID = res.RULE_ID
WHERE res.STATUS = 'FAIL' AND r.IS_CRITICAL = TRUE
ORDER BY res.PASS_RATE ASC
LIMIT 5"""

